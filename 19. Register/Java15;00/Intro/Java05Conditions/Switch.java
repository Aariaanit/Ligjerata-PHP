package Java05Conditions;

public class Switch {
	public static void main(String[] args){
        int i = 1 ;
        switch( i )
        {
            case 1:
                System.out.println( "Numeri eshte 1" );
            break;
            case 2:
                System.out.println( "Numeri eshte 2" );
            break;
            default:
                System.out.println( "Numeri nuk eshte as 1 as 2");
        }
    }
}
